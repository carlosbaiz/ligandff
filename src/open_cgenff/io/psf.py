"""CHARMM PSF writer (XPLOR-style atom types) for a pipeline Result, including halogen lone pairs (NUMLP section).

Used to build OpenMM systems (openmm.app.CharmmPsfFile + CharmmParameterSet with the CGenFF files and the .str).
Lone pairs are appended after the real atoms, in the same order as in the .str residue.
"""


def to_psf(result, masses):
    """PSF text; masses: {atom type: mass} (e.g. ParameterDatabase.file.masses)."""
    lps = result.lone_pairs
    n_real = len(result.atoms)
    rows = [(a.name, a.type, a.charge, masses.get(a.type, 0.0)) for a in result.atoms]
    rows += [(lp.name, lp.type, lp.charge, 0.0) for lp in lps]
    out = ["PSF EXT XPLOR", "", f"{2:10d} !NTITLE", f"* {result.name}", "* generated by open-cgenff", ""]
    out.append(f"{len(rows):10d} !NATOM")
    for k, (name, typ, q, m) in enumerate(rows, 1):
        out.append(f"{k:10d} {'LIG':<8s} {1:<8d} {result.name:<8s} {name:<8s} {typ:<6s} {q:14.6f} {m:14.4f}"
                   f"{0:12d}")
    out.append("")
    by_kind = {"angle": [], "dihedral": [], "improper": []}
    for p in result.assignment.parameters:
        if p.kind in by_kind:
            by_kind[p.kind].append(tuple(i + 1 for i in p.atoms))
    bonds = [(i + 1, j + 1) for i, j in result.bonds]
    for values, title, per in ((bonds, "NBOND: bonds", 4), (by_kind["angle"], "NTHETA: angles", 3),
                               (by_kind["dihedral"], "NPHI: dihedrals", 2),
                               (by_kind["improper"], "NIMPHI: impropers", 2)):
        out.append(f"{len(values):10d} !{title}")
        flat = [x for v in values for x in v]
        chunk = per * (len(values[0]) if values else 1)
        for k in range(0, len(flat), chunk):
            out.append("".join(f"{x:10d}" for x in flat[k:k + chunk]))
        out.append("")
    out += [f"{0:10d} !NDON: donors", "", f"{0:10d} !NACC: acceptors", "", f"{0:10d} !NNB", ""]
    for value, title in ((0, None), (1, "MOLNT")):            # per-atom NNB pointers (all 0), molecule numbers
        if title:
            out.append(f"{1:10d} !{title}")
        for k in range(0, len(rows), 8):
            out.append("".join(f"{value:10d}" for _ in rows[k:k + 8]))
        out.append("")
        if title is None:
            out += [f"{1:10d}{0:10d} !NGRP NST2", f"{0:10d}{0:10d}{0:10d}", ""]
    out.append(f"{len(lps):10d}{3 * len(lps):10d} !NUMLP NUMLPH")
    for k, lp in enumerate(lps):
        out.append(f"{2:10d}{3 * k + 1:10d}   F{lp.distance:14.6f}{0.0:14.6f}{0.0:14.6f}")
    hosts = [x for k, lp in enumerate(lps) for x in (n_real + k + 1, lp.host + 1, lp.base + 1)]
    for k in range(0, len(hosts), 8):
        out.append("".join(f"{x:10d}" for x in hosts[k:k + 8]))
    out.append("")
    return "\n".join(out) + "\n"


def write_psf(result, masses, path):
    with open(path, "w") as fh:
        fh.write(to_psf(result, masses))
