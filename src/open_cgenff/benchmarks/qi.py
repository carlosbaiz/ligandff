"""Set QI: improper dihedrals from typing-rule `impr` actions vs the IMPR lines of the B1/B2 residues (SPEC 5.13).

For every B1/B2 molecule whose atom types the typer gets right, the set of improper centres generated by the rules must
equal the set of first atoms of the residue's IMPR lines. Only centres are compared: the order of the three outer
atoms is resolved when the improper parameter is looked up (params.analogy). Mismatches (with an example molecule) are
listed for development splits only.
"""
import collections

from .common import canonical_type
from .scoring import DEV_SPLITS


def score_impropers(sets, type_molecule, n_examples=30):
    """sets: {name: cases}; type_molecule(rdkit_mol) -> TypedMolecule (types and impropers)."""
    out = {}
    for name, cases in sets.items():
        per_split = collections.defaultdict(lambda: {"molecules": 0, "correct": 0, "reference_centres": 0,
                                                     "missed": 0, "extra": 0})
        wrong = collections.Counter()
        examples = {}
        for case in cases:
            if case.meta.get("impropers") is None:
                continue
            typed = type_molecule(case.mol)
            if any(canonical_type(a) != canonical_type(b) for a, b in zip(typed.types, case.types)):
                continue
            ref = {imp[0] for imp in case.meta["impropers"]}
            got = {imp[0] for imp in typed.impropers}
            s = per_split[case.split]
            s["molecules"] += 1
            s["correct"] += ref == got
            s["reference_centres"] += len(ref)
            s["missed"] += len(ref - got)
            s["extra"] += len(got - ref)
            if case.split in DEV_SPLITS:
                for i in ref ^ got:
                    key = (case.types[i], "missed" if i in ref else "extra")
                    wrong[key] += 1
                    examples.setdefault(key, case.name)
        out[name] = {"splits": dict(per_split),
                     "mismatches": [{"type": t, "kind": k, "count": n, "example": examples[(t, k)]}
                                    for (t, k), n in wrong.most_common(n_examples)]}
    return out
