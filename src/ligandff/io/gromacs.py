"""GROMACS writer for a pipeline Result: <prefix>.itp (molecule), <prefix>.top (standalone system) and <prefix>.gro.

Written directly from our parameter assignment and the CGenFF parameter file (no converter), with the conventions of
the CHARMM36 GROMACS port (comb-rule 2, gen-pairs, fudgeLJ = fudgeQQ = 1):
- bonds funct 1; angles funct 5 (Urey-Bradley, zero when absent); dihedrals funct 9 (one line per CHARMM term);
  impropers funct 2 (harmonic) or 4 (periodic, n > 0). CHARMM force constants (E = k x^2) are doubled for GROMACS
  (E = k x^2 / 2); kcal -> kJ, Angstrom -> nm.
- 1-4 pairs (shortest path of 3 bonds, as CHARMM nbxmod 5) carry explicit CGenFF 1-4 Lennard-Jones parameters (or
  NBFIX), so the .itp does not depend on the force field's [ pairtypes ].
- Halogen lone pairs (CHARMM LONEPAIR COLINEAR) are virtual sites: [ virtual_sites2 ] funct 2 at a fixed distance
  beyond the halogen on the C-X axis. They are excluded from the halogen and the atoms within two bonds of it; other
  interactions are full, as in OpenMM's CHARMM reader (the lone pair has no LJ term and 1-4 electrostatics are unscaled).
- NBFIX pairs between the molecule's types go to [ nonbond_params ] in the .top.
"""
import math

from .. import banner

KCAL = 4.184
SIGMA = 2 ** (-1 / 6)          # sigma = Rmin * 2^(-1/6)


def _lj(pfile, t, one_four=False):
    """(Rmin/2 in Angstrom, |epsilon| in kcal/mol) of a type, 1-4 values when requested and present."""
    eps, rmin2, eps14, rmin14 = pfile.nonbonded[t]
    if one_four and eps14 is not None:
        return rmin14, abs(eps14)
    return rmin2, abs(eps)


def _pair_lj(pfile, a, b, one_four=False):
    """(sigma nm, epsilon kJ/mol) of a type pair: NBFIX if any, else Lorentz-Berthelot of the (1-4) atom values."""
    fix = pfile.nbfix.get((a, b)) or pfile.nbfix.get((b, a))
    if fix is not None:
        emin, rmin = fix
        return rmin * SIGMA / 10, abs(emin) * KCAL
    (ra, ea), (rb, eb) = _lj(pfile, a, one_four), _lj(pfile, b, one_four)
    return (ra + rb) * SIGMA / 10, math.sqrt(ea * eb) * KCAL


def _neighbours(n, bonds):
    adj = [set() for _ in range(n)]
    for i, j in bonds:
        adj[i].add(j)
        adj[j].add(i)
    return adj


def _within(adj, start, depth):
    """{atom: shortest bond distance} for atoms within `depth` bonds of start."""
    dist, frontier = {start: 0}, [start]
    for d in range(1, depth + 1):
        frontier = [k for f in frontier for k in adj[f] if k not in dist]
        for k in frontier:
            dist.setdefault(k, d)
    return dist


def lone_pair_positions(result, xyz):
    """Lone-pair coordinates (same units as xyz): `distance` Angstrom beyond the halogen on the base->host axis."""
    out = []
    for lp in result.lone_pairs:
        h, b = xyz[lp.host], xyz[lp.base]
        v = [h[k] - b[k] for k in range(3)]
        norm = math.sqrt(sum(c * c for c in v))
        out.append(tuple(h[k] + lp.distance * v[k] / norm for k in range(3)))
    return out


def to_itp(result, pfile):
    """[ moleculetype ] text with explicit parameters."""
    n = len(result.atoms)
    name = result.name
    out = [f"; {name}: generated by {banner()}", "; CGenFF-compatible; not the official CGenFF program", "",
           "[ moleculetype ]", "; name  nrexcl", f"{name}  3", "", "[ atoms ]",
           ";   nr  type      resnr resid  atom    cgnr     charge       mass"]
    rows = [(a.type, a.name, a.charge, pfile.masses.get(a.type, 0.0)) for a in result.atoms]
    rows += [(lp.type, lp.name, lp.charge, 0.0) for lp in result.lone_pairs]
    qtot = 0.0
    for k, (typ, aname, q, m) in enumerate(rows, 1):
        qtot += q
        out.append(f"{k:6d}  {typ:<8s} {1:5d}  {name:<5s} {aname:<6s} {k:5d} {q:10.4f} {m:10.4f}   ; qtot {qtot:.3f}")

    by_kind = {"bond": [], "angle": [], "dihedral": [], "improper": []}
    for p in result.assignment.parameters:
        by_kind[p.kind].append(p)
    out += ["", "[ bonds ]", ";  ai    aj funct   b0 (nm)   kb (kJ/mol/nm2)"]
    for p in by_kind["bond"]:
        kb, b0 = p.parameter.values
        i, j = (x + 1 for x in p.atoms)
        out.append(f"{i:5d} {j:5d}     1  {b0 / 10:.7f}  {2 * kb * KCAL * 100:.4f}")

    adj = _neighbours(n, result.bonds)
    pairs = sorted((i, j) for i in range(n) for j, d in _within(adj, i, 3).items() if d == 3 and i < j)
    out += ["", "[ pairs ]", ";  ai    aj funct   sigma (nm)  epsilon (kJ/mol)   CGenFF 1-4 Lennard-Jones"]
    for i, j in pairs:
        sigma, eps = _pair_lj(pfile, result.atoms[i].type, result.atoms[j].type, one_four=True)
        out.append(f"{i + 1:5d} {j + 1:5d}     1  {sigma:.9f}  {eps:.9f}")

    out += ["", "[ angles ]", ";  ai    aj    ak funct  theta0  ktheta (kJ/mol/rad2)  r13 (nm)  kUB (kJ/mol/nm2)"]
    for p in by_kind["angle"]:
        kt, t0, kub, s0 = p.parameter.values
        i, j, k = (x + 1 for x in p.atoms)
        r13, kub = (s0 / 10, 2 * kub * KCAL * 100) if kub else (0.0, 0.0)
        out.append(f"{i:5d} {j:5d} {k:5d}     5  {t0:.5f}  {2 * kt * KCAL:.6f}  {r13:.7f}  {kub:.4f}")

    out += ["", "[ dihedrals ]", ";  ai    aj    ak    al funct  phi0  kphi (kJ/mol)  mult"]
    for p in by_kind["dihedral"]:
        i, j, k, l = (x + 1 for x in p.atoms)
        for kchi, mult, delta in p.parameter.values:
            out.append(f"{i:5d} {j:5d} {k:5d} {l:5d}     9  {delta:.5f}  {kchi * KCAL:.7f}  {mult:d}")

    out += ["", "[ dihedrals ]", "; impropers:  ai    aj    ak    al funct  xi0  kxi (kJ/mol/rad2 for funct 2)"]
    for p in by_kind["improper"]:
        kpsi, mult, psi0 = p.parameter.values
        i, j, k, l = (x + 1 for x in p.atoms)
        if mult:
            out.append(f"{i:5d} {j:5d} {k:5d} {l:5d}     4  {psi0:.5f}  {kpsi * KCAL:.7f}  {mult:d}")
        else:
            out.append(f"{i:5d} {j:5d} {k:5d} {l:5d}     2  {psi0:.5f}  {2 * kpsi * KCAL:.6f}")

    if result.lone_pairs:
        out += ["", "[ virtual_sites2 ]", "; site  host  base funct  a (nm): halogen lone pair, fixed distance on the C-X axis"]
        excl = []
        for k, lp in enumerate(result.lone_pairs):
            site = n + k + 1
            out.append(f"{site:5d} {lp.host + 1:5d} {lp.base + 1:5d}     2  {-lp.distance / 10:.7f}")
            excl.append([site] + sorted(x + 1 for x in _within(adj, lp.host, 2)))
        out += ["", "[ exclusions ]", "; lone pair: excluded like its halogen (itself, 1-2 and 1-3 partners)"]
        out += [" ".join(f"{x:5d}" for x in row) for row in excl]
    return "\n".join(out) + "\n"


def to_top(result, pfile, itp_name):
    """Standalone topology: defaults, atom types and NBFIX of the molecule's types, the .itp, one molecule."""
    types = sorted({a.type for a in result.atoms} | {lp.type for lp in result.lone_pairs})
    out = [f"; {result.name}: standalone topology generated by {banner()}",
           "; CGenFF-compatible; not the official CGenFF program. For a system with CHARMM36 (e.g. protein + ligand),",
           f"; include {itp_name} after the CHARMM36/CGenFF force field instead of this file.", "",
           "[ defaults ]", "; nbfunc  comb-rule  gen-pairs  fudgeLJ  fudgeQQ", "1  2  yes  1.0  1.0", "",
           "[ atomtypes ]", "; name  at.num  mass  charge  ptype  sigma (nm)  epsilon (kJ/mol)"]
    from ..params.database import element_of_mass
    for t in types:
        rmin2, eps = _lj(pfile, t)
        mass = pfile.masses.get(t, 0.0)
        z = element_of_mass(mass)[0] if mass else 0
        out.append(f"{t:<8s} {z:3d}  {mass:9.4f}  0.0  A  {2 * rmin2 * SIGMA / 10:.9f}  {eps * KCAL:.9f}")
    fixes = sorted((a, b) for a, b in pfile.nbfix if a in types and b in types)
    if fixes:
        out += ["", "[ nonbond_params ]", "; i  j  funct  sigma (nm)  epsilon (kJ/mol)   CGenFF NBFIX"]
        for a, b in fixes:
            sigma, eps = _pair_lj(pfile, a, b)
            out.append(f"{a:<8s} {b:<8s} 1  {sigma:.9f}  {eps:.9f}")
    out += ["", f'#include "{itp_name}"', "", "[ system ]", result.name, "", "[ molecules ]", f"{result.name}  1"]
    return "\n".join(out) + "\n"


def to_gro(result, xyz):
    """xyz: Angstrom, real atoms only; lone pairs are placed from their definition."""
    rows = [(a.name, p) for a, p in zip(result.atoms, xyz)]
    rows += [(lp.name, p) for lp, p in zip(result.lone_pairs, lone_pair_positions(result, xyz))]
    lo = [min(p[k] for _, p in rows) for k in range(3)]
    hi = [max(p[k] for _, p in rows) for k in range(3)]
    shift = [1.0 - lo[k] / 10 for k in range(3)]                     # 1 nm margin
    out = [f"{result.name} generated by {banner()}", f"{len(rows):5d}"]
    for k, (aname, p) in enumerate(rows, 1):
        x, y, z = (p[c] / 10 + shift[c] for c in range(3))
        out.append(f"{1:5d}{result.name[:5]:<5s}{aname[:5]:>5s}{k % 100000:5d}{x:8.3f}{y:8.3f}{z:8.3f}")
    out.append("".join(f"{(hi[c] - lo[c]) / 10 + 2.0:10.5f}" for c in range(3)))
    return "\n".join(out) + "\n"
