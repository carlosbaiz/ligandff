"""Writers for pipeline results (SPEC 3, 5.14): CHARMM toppar stream file (.str) and a JSON report.

The .str layout follows the official output (P-II SI Tables S2-S4, P-v5 SI Table S10): an RTF residue with
per-atom charge penalties, then the bonded parameters missing from CGenFF with their analogy source and penalty.
Every file states that it is not from the official CGenFF program (SPEC 2.2).
"""
import json

from .. import banner

PENALTY_GUIDE = ("penalties < 10: analogy fair; 10-50: some basic validation recommended; "
                 "> 50: poor analogy, extensive validation and optimization recommended")
ESTIMATED_NOTE = ("! 'estimated penalty': the analogy needs a substitution never observed among the analogies recorded "
                  "in CGenFF;\n! LigandFF prices such substitutions high, so these values are not on the official "
                  "scale: validate or optimize those terms.")
SECTION = {"bond": "BONDS", "angle": "ANGLES", "dihedral": "DIHEDRALS", "improper": "IMPROPERS"}


def _pen(x):
    """Penalty as printed after `penalty=`: up to three decimals, no trailing zeros (e.g. 0.6, 10, 2.25)."""
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return s if s != "-0" else "0"


def _param_lines(kind, types, prm):
    t = " ".join(f"{x:<6s}" for x in types)
    v = prm.values
    if kind == "bond":
        return [f"{t} {v[0]:9.3f} {v[1]:10.4f}"]
    if kind == "angle":
        line = f"{t} {v[0]:9.3f} {v[1]:10.4f}"
        if v[2] is not None:
            line += f" {v[2]:9.2f} {v[3]:10.5f}"
        return [line]
    if kind == "dihedral":
        return [f"{t} {k:9.4f} {n:3d} {d:8.2f}" for k, n, d in v]
    return [f"{t} {v[0]:9.4f} {v[1]:3d} {v[2]:8.4f}"]


def _estimated_header(result):
    """Header comments for penalties built from unobserved substitutions (RESI and ATOM lines keep the official layout)."""
    atoms = [a.name for a in result.atoms if a.charge_penalty_estimated]
    if not atoms and not any(a.estimated for a in result.analogs.values()):
        return []
    out = [ESTIMATED_NOTE]
    if result.param_penalty_estimated:
        out.append("! The RESI param penalty is estimated.")
    if atoms:
        out.append("! Estimated charge penalties (atoms): " + " ".join(atoms))
    return out


def to_str(result):
    """CHARMM stream file text for a pipeline Result."""
    out = [f"* Toppar stream file generated by {banner()}",
           "* For use with CGenFF version 5.0",
           "*",
           "",
           f"! {PENALTY_GUIDE}",
           *_estimated_header(result),
           "",
           "read rtf card append",
           "* Topologies generated by " + banner(),
           "*",
           "36 1",
           "",
           f"RESI {result.name:<6s} {result.net_charge:7.3f} ! param penalty= {result.param_penalty:7.3f} ; "
           f"charge penalty= {result.charge_penalty:7.3f}",
           "GROUP            ! CHARGE   CH_PENALTY"]
    for a in result.atoms:
        out.append(f"ATOM {a.name:<6s} {a.type:<6s} {a.charge:7.3f} ! {a.charge_penalty:8.3f}")
    for lp in result.lone_pairs:
        out.append(f"ATOM {lp.name:<6s} {lp.type:<6s} {lp.charge:7.3f} ! {0.0:8.3f}")
    out.append("")
    names = [a.name for a in result.atoms]
    for i, j in result.bonds:
        out.append(f"BOND {names[i]:<6s} {names[j]:<6s}")
    for p in result.impropers:
        out.append("IMPR " + " ".join(f"{names[i]:<6s}" for i in p.atoms))
    for lp in result.lone_pairs:
        out.append(f"LONEPAIR COLINEAR {lp.name:<6s} {names[lp.host]:<6s} {names[lp.base]:<6s} "
                   f"DIST {lp.distance:.4f} SCAL 0.0")
    out += ["", "END", "", "read param card flex append",
            "* Parameters generated by analogy by " + banner(), "*", ""]
    analogs = result.analogs
    for kind, section in SECTION.items():
        out.append(section)
        for (k, types), a in analogs.items():
            if k != kind:
                continue
            est = "estimated " if a.estimated else ""
            comment = f"! {result.name}, from {' '.join(a.source)}, {est}penalty= {_pen(a.penalty)}"
            out += [f"{line} {comment}" for line in _param_lines(kind, types, a.parameter)]
        out.append("")
    out += ["END", "RETURN", ""]
    return "\n".join(out)


def to_report(result):
    """Machine-readable report (dict) of a pipeline Result: types, charges, penalties, parameter provenance."""
    names = [a.name for a in result.atoms]
    return {
        "tool": banner(),
        "residue": result.name,
        "net_charge": result.net_charge,
        "param_penalty": round(result.param_penalty, 3),
        "charge_penalty": round(result.charge_penalty, 3),
        "param_penalty_estimated": result.param_penalty_estimated,
        "charge_penalty_estimated": result.charge_penalty_estimated,
        "atoms": [{"name": a.name, "type": a.type, "charge": round(a.charge, 3),
                   "charge_penalty": round(a.charge_penalty, 3), "formal_charge": a.formal_charge,
                   "charge_penalty_estimated": a.charge_penalty_estimated}
                  for a in result.atoms],
        "bonds": [[names[i], names[j]] for i, j in result.bonds],
        "impropers": [[names[i] for i in p.atoms] for p in result.impropers],
        "lone_pairs": [{"name": lp.name, "host": names[lp.host], "base": names[lp.base], "distance": lp.distance,
                        "charge": lp.charge} for lp in result.lone_pairs],
        "analog_parameters": [{"kind": k, "missing": list(t), "source": list(a.source), "penalty": a.penalty,
                               "estimated": a.estimated, "unobserved_substitutions": [list(x) for x in a.unobserved]}
                              for (k, t), a in result.analogs.items()],
        "omitted_dihedrals": [[names[i] for i in atoms] for atoms, _ in result.assignment.omitted],
        "warnings": list(result.warnings),
        "errors": list(result.errors),
    }


def write_str(result, path):
    with open(path, "w") as fh:
        fh.write(to_str(result))


def write_report(result, path):
    with open(path, "w") as fh:
        json.dump(to_report(result), fh, indent=1)
        fh.write("\n")
