def test_lone_pairs_on_aromatic_halogens_only():
    names = ['C1', 'CL1', 'C2', 'CL2', 'LP1']
    types = ['CG2R61', 'CLGR1', 'CG321', 'CLGA1', 'XX']
    lps = lone_pairs(names, types, [(0, 1), (2, 3)])
    assert [(lp.name, lp.host, lp.base, lp.distance) for lp in lps] == [('LP2', 1, 0, 1.64)]   # LP1 name taken
    assert apply_lone_pair_charges([0.0, -0.1, 0.0, -0.2, 0.0], lps)[1] == pytest.approx(-0.15)
    assert LP_DISTANCE == {'CLGR1': 1.64, 'BRGR1': 1.89, 'IGR1': 2.20}


@pytest.fixture(scope='module')
def m064(toppar):
    fx, mol = load_fixture('M064')
    return fx, parameterize_typed(mol, 'M064', toppar)


def test_stream_file_layout_m064(m064):
    fx, r = m064
    text = to_str(r)
    lines = text.splitlines()
    assert lines[0] == f'* Toppar stream file generated by {banner()}'
    assert 'not the official CGenFF program' in lines[0] and lines[1] == '* For use with CGenFF version 5.0'
    assert 'RESI M064     0.000 ! param penalty=   0.600 ; charge penalty=   0.669' in lines
    for a in fx['atoms']:
        assert f"ATOM {a['name']:<6s} {a['type']:<6s} {a['charge']:7.3f} ! {a['charge_penalty']:8.3f}" in lines
    params = [l for l in lines if 'from ' in l]
    source = next(iter(r.analogs.values())).parameter
    assert len(params) == len(source.values)                       # one line per term of the multi-term source
    for line, (k, n, d) in zip(params, source.values):
        assert line == (f'CG311  CG2O5  CG311  CG331  {k:9.4f} {n:3d} {d:8.2f} '
                        '! M064, from CG321 CG2O5 CG311 CG331, penalty= 0.6')
    assert lines.index('read rtf card append') < lines.index('END') < lines.index('read param card flex append')
    assert lines[-1] == 'RETURN'
    assert sum(a.charge for a in r.atoms) == pytest.approx(0.0, abs=1e-9)


def test_report_m064(m064):
    fx, r = m064
    rep = json.loads(json.dumps(to_report(r)))
    assert rep['param_penalty'] == 0.6 and rep['charge_penalty'] == 0.669
    assert [(x['missing'], x['source'], x['penalty']) for x in rep['analog_parameters']] == \
        [(p['missing'], p['source'], p['penalty']) for p in fx['analog_parameters']]
    assert [a['charge'] for a in rep['atoms']] == [a['charge'] for a in fx['atoms']]


def test_pipeline_from_smiles_with_lone_pair(toppar):
    r = parameterize(read_molecule('Clc1ccc(cc1)C(=O)NC', 'CLB'), toppar=toppar)
    assert r.name == 'CLB' and not r.errors and len(r.lone_pairs) == 1
    cl = next(i for i, a in enumerate(r.atoms) if a.type == 'CLGR1')
    assert r.lone_pairs[0].host == cl
    assert sum(a.charge for a in r.atoms) + sum(lp.charge for lp in r.lone_pairs) == pytest.approx(r.net_charge)
    text = to_str(r)
    assert 'LONEPAIR COLINEAR LP1    Cl1    C2     DIST 1.6400 SCAL 0.0' in text
    assert 'IMPR C8     C5     N10    O9' in text                     # amide improper in parameter-file order


def test_openmm_system_with_lone_pair(toppar):
    openmm = pytest.importorskip('openmm')
    from open_cgenff.export import openmm_system, potential_energy
    r = parameterize(read_molecule('Clc1ccc(cc1)C(=O)NC', 'CLB'), toppar=toppar)
    system, psf, pos = openmm_system(r, toppar)
    n = len(r.atoms) + 1
    assert system.getNumParticles() == n and system.isVirtualSite(n - 1)
    assert math.isfinite(potential_energy(system, pos))
    # the virtual site sits on the C-Cl axis, 1.64 A beyond Cl
    p = [v.value_in_unit(openmm.unit.angstrom) for v in (pos[r.lone_pairs[0].base], pos[r.lone_pairs[0].host],
                                                         pos[n - 1])]
    d = lambda a, b: math.dist(tuple(a), tuple(b))
    assert d(p[1], p[2]) == pytest.approx(1.64, abs=1e-3)
    assert d(p[0], p[2]) == pytest.approx(d(p[0], p[1]) + 1.64, abs=1e-3)


def test_b3_molecules_build_in_openmm(toppar):
    """M6 acceptance: every B3 molecule goes through the pipeline and builds an OpenMM system."""
    pytest.importorskip('openmm')
    from open_cgenff.benchmarks import b3
    from open_cgenff.export import openmm_system, potential_energy
    from open_cgenff.molecule import InputMolecule
    cases, _ = b3.build()
    assert len(cases) == 34
    for c in cases:
        r = parameterize(InputMolecule.from_rdkit(c.mol, c.name), 'MOL', toppar)
        assert not r.errors, c.name
        system, _, pos = openmm_system(r, toppar)
        assert system.getNumParticles() == len(r.atoms) + len(r.lone_pairs)
        assert math.isfinite(potential_energy(system, pos)), c.name


def test_cli_writes_stream_json_and_psf(toppar, tmp_path, capsys):
    out, rep, psf = tmp_path / 'x.str', tmp_path / 'x.json', tmp_path / 'x.psf'
    rc = cli_main(['CC(=O)[O-]', '--name', 'ACET', '-o', str(out), '--json', str(rep), '--psf', str(psf),
                   '--toppar', toppar])
    assert rc == 0
    assert 'RESI ACET    -1.000' in out.read_text()
    assert json.loads(rep.read_text())['net_charge'] == -1
    assert '!NATOM' in psf.read_text() and '!NUMLP NUMLPH' in psf.read_text()
    assert 'param penalty' in capsys.readouterr().err
    rc = cli_main(['CCO', '--toppar', toppar])
    assert rc == 0 and 'RESI LIG' in capsys.readouterr().out


def test_gromacs_export(toppar, tmp_path):
    pytest.importorskip('openmm')
    pytest.importorskip('parmed')
    from open_cgenff.export import write_gromacs
    r = parameterize(read_molecule('Clc1ccccc1C(=O)O', 'CBA'), toppar=toppar)
    top, gro = write_gromacs(r, str(tmp_path / 'cba'), toppar)
    assert 'CLGR1' in open(top).read() and len(open(gro).read().splitlines()) == len(r.atoms) + 1 + 3
